-- ElevenRoute core schema. Runs on Supabase Postgres and on local PGlite.
-- Every row belongs to a workspace; each user gets a personal workspace on first sign-in.
-- Timestamps are epoch milliseconds (double precision) to match the API and the clients.

create table if not exists workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists workspace_members (
  workspace_id uuid not null references workspaces(id) on delete cascade,
  user_id uuid not null,
  role text not null default 'owner' check (role in ('owner', 'member')),
  created_at timestamptz not null default now(),
  primary key (workspace_id, user_id)
);
create index if not exists workspace_members_user on workspace_members(user_id);

-- Routing configuration per workspace: models, strategy, rules, policies, languages, segments, mode.
create table if not exists workspace_settings (
  workspace_id uuid not null references workspaces(id) on delete cascade,
  key text not null,
  value jsonb not null,
  updated_at timestamptz not null default now(),
  primary key (workspace_id, key)
);

create table if not exists turns (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references workspaces(id) on delete cascade,
  ts double precision not null,
  conversation_id text not null,
  customer_id text not null,
  language text not null,
  use_case text not null,
  turn_type text not null,
  model_id text,
  vendor text,
  tokens_in integer not null,
  tokens_out integer not null,
  cost double precision not null,
  latency_ms double precision not null,
  overhead_ms double precision not null,
  failover boolean not null,
  failover_from text,
  failover_reason text,
  synthetic boolean not null
);
create index if not exists turns_workspace_ts on turns(workspace_id, ts);

create table if not exists test_runs (
  id integer generated by default as identity primary key,
  workspace_id uuid not null references workspaces(id) on delete cascade,
  ts double precision not null,
  mode text not null,
  scores jsonb not null
);
create index if not exists test_runs_workspace on test_runs(workspace_id, id desc);

create table if not exists test_results (
  run_id integer not null references test_runs(id) on delete cascade,
  workspace_id uuid not null references workspaces(id) on delete cascade,
  model_id text not null,
  case_id text not null,
  use_case text not null,
  language text not null,
  turn_type text not null,
  completed boolean not null,
  accuracy double precision not null,
  tone double precision not null,
  latency_ms double precision not null,
  score double precision not null,
  reply text not null
);
create index if not exists test_results_run on test_results(run_id);

create table if not exists alerts (
  id integer generated by default as identity primary key,
  workspace_id uuid not null references workspaces(id) on delete cascade,
  ts double precision not null,
  model_id text not null,
  message text not null
);
create index if not exists alerts_workspace on alerts(workspace_id, id desc);
